// protoc-gen-go-origincloud generates a REST client per service of the
// Origin Cloud APIs, next to the messages protoc-gen-go generates: one
// method per RPC, sent as its google.api.http binding with proto3's JSON
// mapping, through the core package.
//
// A method answering with a long-running operation returns a
// core.Operation of the result its operation_info names. A list method
// (AIP-158) also gets an All... method iterating over every page. A
// method with a request_id gets one filled in when it is empty, so that
// it is safe to retry.
package main

import (
	"fmt"
	"regexp"
	"strings"
	"unicode"
	"unicode/utf8"

	"cloud.google.com/go/longrunning/autogen/longrunningpb"
	"google.golang.org/genproto/googleapis/api/annotations"
	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/types/pluginpb"
)

// The services that answer only at their regionless host
// (docs: "Global services have only the regionless name").
var globalServices = map[string]bool{"iam": true, "admin": true, "location": true}

const (
	corePackage    = protogen.GoImportPath("go.origincloud.eu/sdk/core")
	contextPackage = protogen.GoImportPath("context")
	httpPackage    = protogen.GoImportPath("net/http")
	iterPackage    = protogen.GoImportPath("iter")
	protoPackage   = protogen.GoImportPath("google.golang.org/protobuf/proto")

	operationType = "google.longrunning.Operation"
	emptyType     = "google.protobuf.Empty"
)

func main() {
	protogen.Options{}.Run(func(gen *protogen.Plugin) error {
		gen.SupportedFeatures = uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL)
		messages := map[protoreflect.FullName]*protogen.Message{}
		for _, f := range gen.Files {
			collect(messages, f.Messages)
		}
		for _, f := range gen.Files {
			if !f.Generate || len(f.Services) == 0 {
				continue
			}
			if err := generateFile(gen, f, messages); err != nil {
				return err
			}
		}
		return nil
	})
}

func collect(into map[protoreflect.FullName]*protogen.Message, messages []*protogen.Message) {
	for _, m := range messages {
		into[m.Desc.FullName()] = m
		collect(into, m.Messages)
	}
}

func generateFile(gen *protogen.Plugin, f *protogen.File, messages map[protoreflect.FullName]*protogen.Message) error {
	g := gen.NewGeneratedFile(f.GeneratedFilenamePrefix+"_client.pb.go", f.GoImportPath)
	g.P("// Code generated by protoc-gen-go-origincloud. DO NOT EDIT.")
	g.P("// source: ", f.Desc.Path())
	g.P()
	g.P("package ", f.GoPackageName)
	for _, s := range f.Services {
		if err := generateService(g, f, s, messages); err != nil {
			return fmt.Errorf("%s: %w", s.Desc.FullName(), err)
		}
	}
	return nil
}

func generateService(g *protogen.GeneratedFile, f *protogen.File, s *protogen.Service, messages map[protoreflect.FullName]*protogen.Message) error {
	client := strings.TrimSuffix(s.GoName, "Service") + "Client"
	coreService := g.QualifiedGoIdent(corePackage.Ident("Service"))
	coreClient := g.QualifiedGoIdent(corePackage.Ident("Client"))

	g.P()
	g.P("// ", client, " calls ", s.Desc.Name(), ".")
	if doc := comment(s.Comments.Leading); doc != "" {
		g.P("//")
		writeDoc(g, doc)
	}
	g.P("type ", client, " struct {")
	g.P("service *", coreService)
	g.P("}")
	g.P()

	host := proto.GetExtension(s.Desc.Options(), annotations.E_DefaultHost).(string)
	if host != "" {
		shortcode, _, _ := strings.Cut(host, ".")
		g.P("// New", client, " returns a client of ", s.Desc.Name(), " that sends its calls through client.")
		g.P("func New", client, "(client *", coreClient, ") *", client, " {")
		g.P("return &", client, "{service: client.Service(", fmt.Sprintf("%q", shortcode), ", ", !globalServices[shortcode], ")}")
		g.P("}")
		g.P()
		g.P("// Service returns the endpoint the client sends its calls to, which")
		g.P("// also serves the operations its methods answer with.")
		g.P("func (c *", client, ") Service() *", coreService, " {")
		g.P("return c.service")
		g.P("}")
	} else {
		g.P("// New", client, " returns a client of ", s.Desc.Name(), " at service, the endpoint")
		g.P("// of another service's client: every service serves it at its own host.")
		g.P("func New", client, "(service *", coreService, ") *", client, " {")
		g.P("return &", client, "{service: service}")
		g.P("}")
	}

	for _, m := range s.Methods {
		if err := generateMethod(g, client, m, messages); err != nil {
			return fmt.Errorf("%s: %w", m.Desc.Name(), err)
		}
		if list := listOf(m); list != nil {
			generateAll(g, client, m, list)
		}
	}
	return nil
}

// A google.api.http path template, split into literals and variables.
type segment struct {
	literal string
	field   []*protogen.Field
	pattern string
}

func generateMethod(g *protogen.GeneratedFile, client string, m *protogen.Method, messages map[protoreflect.FullName]*protogen.Message) error {
	rule, _ := proto.GetExtension(m.Desc.Options(), annotations.E_Http).(*annotations.HttpRule)
	if rule == nil {
		return fmt.Errorf("no google.api.http binding")
	}
	verb, template := binding(rule)
	if template == "" || len(rule.GetAdditionalBindings()) > 0 {
		return fmt.Errorf("one binding with a path is supported")
	}
	segments, err := parseTemplate(m.Input, template)
	if err != nil {
		return err
	}

	ctx := g.QualifiedGoIdent(contextPackage.Ident("Context"))
	input := g.QualifiedGoIdent(m.Input.GoIdent)
	result, operationResult, err := resultOf(g, m, messages)
	if err != nil {
		return err
	}

	g.P()
	writeMethodDoc(g, m, operationResult)
	g.P("func (c *", client, ") ", m.GoName, "(ctx ", ctx, ", req *", input, ") (", result, ", error) {")

	requestID := fieldNamed(m.Input, "request_id")
	idempotent := verb == "GET" || requestID != nil
	if requestID != nil {
		g.P("if req.Get", requestID.GoName, "() == \"\" {")
		g.P("req = ", g.QualifiedGoIdent(protoPackage.Ident("Clone")), "(req).(*", input, ")")
		g.P("req.", requestID.GoName, " = ", g.QualifiedGoIdent(corePackage.Ident("NewRequestID")), "()")
		g.P("}")
	}

	var path []string
	var bound []string
	for i, s := range segments {
		if s.field == nil {
			path = append(path, fmt.Sprintf("%q", s.literal))
			continue
		}
		jsonPath, getter := fieldPath(s.field)
		bound = append(bound, jsonPath)
		g.P(fmt.Sprintf("p%d, err := ", i), g.QualifiedGoIdent(corePackage.Ident("PathValue")),
			fmt.Sprintf("(%q, req%s, %q)", jsonPath, getter, s.pattern))
		g.P("if err != nil {")
		g.P("return nil, err")
		g.P("}")
		path = append(path, fmt.Sprintf("p%d", i))
	}

	request := []string{
		"Method: " + g.QualifiedGoIdent(httpPackage.Ident(httpMethod(verb))) + ",",
		"Path: " + strings.Join(path, " + ") + ",",
	}
	switch body := rule.GetBody(); body {
	case "*":
		request = append(request, "Body: req,")
	default:
		skip := bound
		if body != "" {
			field := fieldNamed(m.Input, body)
			if field == nil {
				return fmt.Errorf("the body field %s isn't a field of %s", body, m.Input.Desc.Name())
			}
			skip = append(skip, field.Desc.JSONName())
			request = append(request, "Body: req.Get"+field.GoName+"(),")
		}
		quoted := make([]string, len(skip))
		for i, s := range skip {
			quoted[i] = fmt.Sprintf("%q", s)
		}
		g.P("query, err := ", g.QualifiedGoIdent(corePackage.Ident("Query")), "(req, ", strings.Join(quoted, ", "), ")")
		g.P("if err != nil {")
		g.P("return nil, err")
		g.P("}")
		request = append(request, "Query: query,")
	}
	if idempotent {
		request = append(request, "Idempotent: true,")
	}

	g.P("out := new(", g.QualifiedGoIdent(m.Output.GoIdent), ")")
	g.P("if err := c.service.Call(ctx, ", g.QualifiedGoIdent(corePackage.Ident("Request")), "{")
	for _, line := range request {
		g.P(line)
	}
	g.P("}, out); err != nil {")
	g.P("return nil, err")
	g.P("}")
	if operationResult != nil {
		g.P("return ", g.QualifiedGoIdent(corePackage.Ident("NewOperation")), "[*",
			g.QualifiedGoIdent(operationResult.GoIdent), "](c.service, out), nil")
	} else {
		g.P("return out, nil")
	}
	g.P("}")
	return nil
}

// resultOf returns what a method returns, and for one answering with a
// long-running operation, the message of the operation's result.
func resultOf(g *protogen.GeneratedFile, m *protogen.Method, messages map[protoreflect.FullName]*protogen.Message) (string, *protogen.Message, error) {
	output := "*" + g.QualifiedGoIdent(m.Output.GoIdent)
	info, _ := proto.GetExtension(m.Desc.Options(), longrunningpb.E_OperationInfo).(*longrunningpb.OperationInfo)
	if m.Output.Desc.FullName() != operationType || info == nil {
		return output, nil, nil
	}
	name := protoreflect.FullName(info.GetResponseType())
	if !strings.Contains(string(name), ".") {
		name = m.Desc.ParentFile().Package().Append(name.Name())
	}
	result, ok := messages[name]
	if !ok {
		return "", nil, fmt.Errorf("the operation's response type %s isn't defined", name)
	}
	operation := g.QualifiedGoIdent(corePackage.Ident("Operation"))
	return "*" + operation + "[*" + g.QualifiedGoIdent(result.GoIdent) + "]", result, nil
}

// A list method (AIP-158): its request takes a page token and its response
// carries the next one and one repeated field of messages.
func listOf(m *protogen.Method) *protogen.Field {
	if fieldNamed(m.Input, "page_token") == nil || fieldNamed(m.Output, "next_page_token") == nil {
		return nil
	}
	var items *protogen.Field
	for _, f := range m.Output.Fields {
		if f.Desc.IsList() && f.Message != nil {
			if items != nil {
				return nil
			}
			items = f
		}
	}
	return items
}

func generateAll(g *protogen.GeneratedFile, client string, m *protogen.Method, items *protogen.Field) {
	ctx := g.QualifiedGoIdent(contextPackage.Ident("Context"))
	input := g.QualifiedGoIdent(m.Input.GoIdent)
	item := "*" + g.QualifiedGoIdent(items.Message.GoIdent)
	seq := g.QualifiedGoIdent(iterPackage.Ident("Seq2"))
	name := "All" + items.GoName
	g.P()
	g.P("// ", name, " returns everything ", m.GoName, " lists from req's page on, fetching")
	g.P("// the next page as the loop reaches it. A page that fails ends the sequence")
	g.P("// with its error.")
	g.P("func (c *", client, ") ", name, "(ctx ", ctx, ", req *", input, ") ", seq, "[", item, ", error] {")
	g.P("return func(yield func(", item, ", error) bool) {")
	g.P("req := ", g.QualifiedGoIdent(protoPackage.Ident("Clone")), "(req).(*", input, ")")
	g.P("for {")
	g.P("page, err := c.", m.GoName, "(ctx, req)")
	g.P("if err != nil {")
	g.P("yield(nil, err)")
	g.P("return")
	g.P("}")
	g.P("for _, item := range page.Get", items.GoName, "() {")
	g.P("if !yield(item, nil) {")
	g.P("return")
	g.P("}")
	g.P("}")
	g.P("if page.GetNextPageToken() == \"\" {")
	g.P("return")
	g.P("}")
	g.P("req.PageToken = page.GetNextPageToken()")
	g.P("}")
	g.P("}")
	g.P("}")
}

func binding(rule *annotations.HttpRule) (string, string) {
	switch p := rule.GetPattern().(type) {
	case *annotations.HttpRule_Get:
		return "GET", p.Get
	case *annotations.HttpRule_Post:
		return "POST", p.Post
	case *annotations.HttpRule_Put:
		return "PUT", p.Put
	case *annotations.HttpRule_Patch:
		return "PATCH", p.Patch
	case *annotations.HttpRule_Delete:
		return "DELETE", p.Delete
	default:
		return "", ""
	}
}

func httpMethod(verb string) string {
	return "Method" + verb[:1] + strings.ToLower(verb[1:])
}

// parseTemplate splits a path template, such as
// "/v1beta1/{name=projects/*/zones/*/volumes/*}:wait", into literals and
// the fields its variables bind.
func parseTemplate(input *protogen.Message, template string) ([]segment, error) {
	var segments []segment
	for rest := template; rest != ""; {
		open := strings.IndexByte(rest, '{')
		if open < 0 {
			segments = append(segments, segment{literal: rest})
			break
		}
		if open > 0 {
			segments = append(segments, segment{literal: rest[:open]})
		}
		end := strings.IndexByte(rest, '}')
		if end < open {
			return nil, fmt.Errorf("unbalanced braces in %s", template)
		}
		name, pattern, found := strings.Cut(rest[open+1:end], "=")
		if !found {
			pattern = "*"
		}
		if strings.Contains(pattern, "**") {
			return nil, fmt.Errorf("%s: ** isn't supported", template)
		}
		field, err := resolveField(input, name)
		if err != nil {
			return nil, err
		}
		segments = append(segments, segment{field: field, pattern: pattern})
		rest = rest[end+1:]
	}
	return segments, nil
}

// resolveField finds the string field a dotted path names.
func resolveField(message *protogen.Message, path string) ([]*protogen.Field, error) {
	var fields []*protogen.Field
	for i, name := range strings.Split(path, ".") {
		if i > 0 {
			message = fields[i-1].Message
		}
		field := fieldNamed(message, name)
		if field == nil {
			return nil, fmt.Errorf("the path variable %s isn't a field", path)
		}
		fields = append(fields, field)
	}
	last := fields[len(fields)-1]
	if last.Desc.Kind() != protoreflect.StringKind || last.Desc.IsList() {
		return nil, fmt.Errorf("the path variable %s isn't a string field", path)
	}
	return fields, nil
}

func fieldNamed(message *protogen.Message, name string) *protogen.Field {
	if message == nil {
		return nil
	}
	for _, f := range message.Fields {
		if string(f.Desc.Name()) == name {
			return f
		}
	}
	return nil
}

// fieldPath returns a field path's JSON path and the getters reading it.
func fieldPath(fields []*protogen.Field) (string, string) {
	var json, getter strings.Builder
	for i, f := range fields {
		if i > 0 {
			json.WriteByte('.')
		}
		json.WriteString(f.Desc.JSONName())
		getter.WriteString(".Get" + f.GoName + "()")
	}
	return json.String(), getter.String()
}

func writeMethodDoc(g *protogen.GeneratedFile, m *protogen.Method, operationResult *protogen.Message) {
	doc := comment(m.Comments.Leading)
	if doc == "" {
		g.P("// ", m.GoName, " calls ", m.Desc.Name(), ".")
	} else {
		writeDoc(g, m.GoName+" "+lowerFirst(doc))
	}
	switch {
	case operationResult == nil:
	case operationResult.Desc.FullName() == emptyType:
		g.P("//")
		g.P("// It answers with an operation to wait on, which has no result.")
	default:
		g.P("//")
		g.P("// It answers with an operation to wait on, whose result is the ", operationResult.Desc.Name(), ".")
	}
}

// A proto comment without the API linter's directives, `(-- ... --)`.
var linterDirective = regexp.MustCompile(`(?s)\(--.*?--\)`)

func comment(c protogen.Comments) string {
	return strings.TrimSpace(linterDirective.ReplaceAllString(string(c), ""))
}

func writeDoc(g *protogen.GeneratedFile, doc string) {
	for _, line := range strings.Split(doc, "\n") {
		line = strings.TrimRightFunc(line, unicode.IsSpace)
		if line == "" {
			g.P("//")
		} else {
			g.P("// ", strings.TrimPrefix(line, " "))
		}
	}
}

// lowerFirst lowers a sentence's first letter, so that it reads after the
// method's name: "Returns a volume." becomes "returns a volume.".
func lowerFirst(s string) string {
	r, size := utf8.DecodeRuneInString(s)
	next, _ := utf8.DecodeRuneInString(s[size:])
	if unicode.IsUpper(next) {
		return s // an acronym
	}
	return string(unicode.ToLower(r)) + s[size:]
}
